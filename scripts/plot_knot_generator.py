_REPO_ROOT = str(Path(__file__).resolve().parent.parent)
if _REPO_ROOT not in sys.path or sys.path[0] != _REPO_ROOT:
    sys.path.insert(0, _REPO_ROOT)

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import torch
import numpy as np

from repc.data import generate_knot_distribution
from repc.flow import ALICFMGeneratorWrapper


def parse_args():
    parser = argparse.ArgumentParser(description="Plot trajectories generated by Knot generator")
    parser.add_argument("--checkpoint", type=Path, required=True, help="Path to generator checkpoint")
    parser.add_argument("--output", type=Path, default=Path("outputs/knot_generator_trajectories.png"))
    parser.add_argument("--num-trajectories", type=int, default=100)
    parser.add_argument("--num-steps", type=int, default=100)
    parser.add_argument("--K", type=int, default=60, help="Number of ground truth marginals")
    parser.add_argument("--device", default="auto")
    return parser.parse_args()


@torch.no_grad()
def get_generator_trajectories(generator, x0, x1, num_steps, device):
    time_steps = torch.linspace(0.0, 1.0, num_steps + 1, device=device)
    trajectories = []
    for t_val in time_steps:
        # The generator wrapper expects 1D or 0D time tensor
        t = t_val.expand(x0.shape[0])
        x_t = generator(x0, x1, t)
        trajectories.append(x_t)
    return torch.stack(trajectories, dim=1)


def main():
    args = parse_args()
    device = torch.device(
        ("cuda" if torch.cuda.is_available() else "cpu") if args.device == "auto" else args.device
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)

    print(f"Loading generator from {args.checkpoint}...")
    generator = ALICFMGeneratorWrapper(str(args.checkpoint)).to(device)
    generator.eval()

    print(f"Generating ground truth Knot distribution (K={args.K})...")
    gt_data = generate_knot_distribution(K=args.K, samples_per_marginal=100)
    K, N, _ = gt_data.shape

    # Sample source and target coordinates
    init_indices = torch.randint(0, N, (args.num_trajectories,))
    x0 = gt_data[0, init_indices].to(device)
    target_indices = torch.randint(0, N, (args.num_trajectories,))
    x1 = gt_data[-1, target_indices].to(device)

    print(f"Evaluating generator for {args.num_trajectories} trajectories...")
    trajectories = get_generator_trajectories(generator, x0, x1, num_steps=args.num_steps, device=device)

    traj_np = trajectories.cpu().numpy()
    gt_np = gt_data.numpy()

    # ---- Plot ----
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
    fig, ax = plt.subplots(figsize=(8, 8), dpi=150)

    cmap = plt.cm.viridis
    for k in range(K):
        color = cmap(k / (K - 1))
        ax.scatter(gt_np[k, :, 0], gt_np[k, :, 1], color=color, alpha=0.15, s=6)

    for b in range(args.num_trajectories):
        ax.plot(traj_np[b, :, 0], traj_np[b, :, 1], color="crimson", alpha=0.5, linewidth=1.0)

    ax.scatter(traj_np[:, 0, 0], traj_np[:, 0, 1], color="forestgreen", s=30, zorder=5, label="Start")
    ax.scatter(traj_np[:, -1, 0], traj_np[:, -1, 1], color="purple", s=30, zorder=5, label="End")

    # Fixed axis limits to match the other scripts
    ax.set_xlim(-5, 5)
    ax.set_ylim(-3, 3)
    ax.set_aspect("equal")

    title = "Generator ODE Path (Knot)"
    ax.set_title(title, fontsize=14, fontweight="bold")
    ax.set_xlabel("X")
    ax.set_ylabel("Y")
    ax.legend(loc="upper right", frameon=True)

    plt.tight_layout()
    plt.savefig(args.output, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"Plot saved to {args.output}")


if __name__ == "__main__":
    main()
