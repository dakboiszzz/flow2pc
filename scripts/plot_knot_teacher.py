import argparse
import sys
from pathlib import Path

# Ensure local repository root takes precedence over any installed site-packages
_REPO_ROOT = str(Path(__file__).resolve().parent.parent)
if _REPO_ROOT not in sys.path or sys.path[0] != _REPO_ROOT:
    sys.path.insert(0, _REPO_ROOT)

import matplotlib.pyplot as plt
import numpy as np
import torch
from repc.data import generate_knot_distribution
from repc.flow import ALICFMTeacherWrapper


def parse_args():
    parser = argparse.ArgumentParser(description="Plot trajectories generated by Knot ALI-CFM teacher")
    parser.add_argument(
        "--checkpoint",
        type=Path,
        default=Path("checkpoints/knot_alicfm_teacher.pt"),
        help="Path to teacher checkpoint",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("outputs/knot_teacher_trajectories.png"),
        help="Output image path",
    )
    parser.add_argument("--num-trajectories", type=int, default=30, help="Number of trajectories to simulate")
    parser.add_argument("--num-steps", type=int, default=100, help="Number of RK4 ODE integration steps")
    parser.add_argument("--K", type=int, default=60, help="Number of ground truth marginals")
    parser.add_argument("--device", default="auto", help="Device to run ODE on")
    return parser.parse_args()


@torch.no_grad()
def integrate_rk4(
    teacher: ALICFMTeacherWrapper,
    x0: torch.Tensor,
    num_steps: int = 100,
    device: torch.device = torch.device("cpu"),
) -> tuple[torch.Tensor, torch.Tensor]:
    """Integrate dx/dt = v(t, x) from t=0 to t=1 using Runge-Kutta 4th order."""
    dt = 1.0 / num_steps
    time_steps = torch.linspace(0.0, 1.0, num_steps + 1, device=device)
    
    trajectories = [x0.clone()]
    current_x = x0.clone()

    for i in range(num_steps):
        t_curr = time_steps[i].repeat(current_x.shape[0])
        t_mid = (time_steps[i] + 0.5 * dt).repeat(current_x.shape[0])
        t_next = time_steps[i + 1].repeat(current_x.shape[0])

        k1 = teacher(t_curr, current_x)
        k2 = teacher(t_mid, current_x + 0.5 * dt * k1)
        k3 = teacher(t_mid, current_x + 0.5 * dt * k2)
        k4 = teacher(t_next, current_x + dt * k3)

        current_x = current_x + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
        trajectories.append(current_x.clone())

    # [num_steps + 1, batch_size, 2] -> [batch_size, num_steps + 1, 2]
    traj_tensor = torch.stack(trajectories, dim=1)
    return time_steps, traj_tensor


def main():
    args = parse_args()
    device = torch.device(
        ("cuda" if torch.cuda.is_available() else "cpu")
        if args.device == "auto"
        else args.device
    )

    args.output.parent.mkdir(parents=True, exist_ok=True)

    print(f"Loading teacher from {args.checkpoint}...")
    teacher = ALICFMTeacherWrapper(args.checkpoint, num_marginals=args.K)
    teacher.to(device)
    teacher.eval()

    print(f"Generating ground truth Knot distribution (K={args.K})...")
    gt_data = generate_knot_distribution(K=args.K, samples_per_marginal=100)  # [K, N, 2]
    K, N, _ = gt_data.shape

    # Initial condition: sample from marginal 0
    init_indices = torch.randint(0, N, (args.num_trajectories,))
    x0 = gt_data[0, init_indices].to(device)

    print(f"Simulating {args.num_trajectories} trajectories via RK4 ({args.num_steps} steps)...")
    time_steps, trajectories = integrate_rk4(teacher, x0, num_steps=args.num_steps, device=device)
    traj_np = trajectories.cpu().numpy()  # [B, S+1, 2]
    gt_np = gt_data.numpy()

    # Quantitative diagnostics
    start_sim = traj_np[:, 0, :]
    end_sim = traj_np[:, -1, :]
    start_gt = gt_np[0]
    end_gt = gt_np[-1]

    print(f"Initial GT Mean:  {start_gt.mean(axis=0)} | Sim Mean: {start_sim.mean(axis=0)}")
    print(f"Final   GT Mean:  {end_gt.mean(axis=0)}   | Sim Mean: {end_sim.mean(axis=0)}")

    # Plotting
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
    fig = plt.figure(figsize=(18, 5), dpi=200)

    # 1. Main Trajectories vs Ground Truth Marginals
    ax1 = fig.add_subplot(1, 3, 1)
    cmap = plt.cm.viridis
    for k in range(K):
        color = cmap(k / (K - 1))
        ax1.scatter(gt_np[k, :, 0], gt_np[k, :, 1], color=color, alpha=0.15, s=6)

    for b in range(args.num_trajectories):
        ax1.plot(
            traj_np[b, :, 0],
            traj_np[b, :, 1],
            color="crimson",
            alpha=0.6,
            linewidth=1.2,
        )
    ax1.scatter(traj_np[:, 0, 0], traj_np[:, 0, 1], color="forestgreen", s=30, zorder=5, label=r"Start ($t=0$)")
    ax1.scatter(traj_np[:, -1, 0], traj_np[:, -1, 1], color="purple", s=30, zorder=5, label=r"End ($t=1$)")
    ax1.set_title("Knot Teacher Trajectories vs Ground Truth Marginals", fontsize=11, fontweight="bold")
    ax1.set_xlabel("X")
    ax1.set_ylabel("Y")
    ax1.legend(loc="upper right", frameon=True)
    ax1.set_aspect("equal")

    # 2. Intermediate Marginal Snapshot Comparisons
    ax2 = fig.add_subplot(1, 3, 2)
    selected_fractions = [0.0, 0.25, 0.5, 0.75, 1.0]
    colors = ["#2b5c8f", "#3a927c", "#c98236", "#d95f02", "#7570b3"]
    for frac, color in zip(selected_fractions, colors):
        k_idx = int(round(frac * (K - 1)))
        step_idx = int(round(frac * args.num_steps))
        # GT points
        ax2.scatter(
            gt_np[k_idx, :, 0],
            gt_np[k_idx, :, 1],
            color=color,
            alpha=0.25,
            s=12,
            label=f"t={frac:.2f} (GT)",
        )
        # Simulated ODE particles
        ax2.scatter(
            traj_np[:, step_idx, 0],
            traj_np[:, step_idx, 1],
            facecolors="none",
            edgecolors=color,
            s=40,
            linewidths=1.5,
            label=f"t={frac:.2f} (Sim)",
        )
    ax2.set_title("Intermediate Marginal Snapshots (GT vs Sim)", fontsize=11, fontweight="bold")
    ax2.set_xlabel("X")
    ax2.set_ylabel("Y")
    ax2.legend(loc="upper right", fontsize=8, frameon=True, ncol=2)
    ax2.set_aspect("equal")

    # 3. Vector Field Flow at Midpoint t=0.5
    ax3 = fig.add_subplot(1, 3, 3)
    x_min, x_max = gt_np[..., 0].min() - 0.5, gt_np[..., 0].max() + 0.5
    y_min, y_max = gt_np[..., 1].min() - 0.5, gt_np[..., 1].max() + 0.5
    grid_x, grid_y = np.meshgrid(
        np.linspace(x_min, x_max, 25),
        np.linspace(y_min, y_max, 25),
    )
    grid_points = torch.tensor(
        np.stack([grid_x.flatten(), grid_y.flatten()], axis=-1),
        dtype=torch.float32,
        device=device,
    )
    t_mid = torch.tensor([0.5] * len(grid_points), dtype=torch.float32, device=device)
    with torch.no_grad():
        v_mid = teacher(t_mid, grid_points).cpu().numpy()

    u = v_mid[:, 0].reshape(grid_x.shape)
    v = v_mid[:, 1].reshape(grid_y.shape)
    speed = np.sqrt(u**2 + v**2) + 1e-6
    ax3.quiver(
        grid_x,
        grid_y,
        u / speed,
        v / speed,
        speed,
        cmap="plasma",
        alpha=0.8,
        pivot="mid",
    )
    # Overlay ground truth curve points around t=0.5
    k_mid = K // 2
    ax3.scatter(gt_np[k_mid, :, 0], gt_np[k_mid, :, 1], color="black", s=15, alpha=0.5, label="GT points (t=0.5)")
    ax3.set_title(r"Learned Velocity Vector Field $v_\theta(x, t=0.5)$", fontsize=11, fontweight="bold")
    ax3.set_xlabel("X")
    ax3.set_ylabel("Y")
    ax3.legend(loc="upper right", frameon=True)
    ax3.set_aspect("equal")

    plt.tight_layout()
    plt.savefig(args.output, dpi=200, bbox_inches="tight")
    plt.close()
    print(f"Trajectory visualization saved successfully to {args.output}")


if __name__ == "__main__":
    main()
