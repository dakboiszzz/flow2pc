import sys
from pathlib import Path

_REPO_ROOT = str(Path(__file__).resolve().parent.parent)
if _REPO_ROOT not in sys.path or sys.path[0] != _REPO_ROOT:
    sys.path.insert(0, _REPO_ROOT)

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch
import wandb

from repc.data import generate_knot_distribution
from repc.flow import ALICFMTeacherWrapper
from train import build_student


def parse_args():
    parser = argparse.ArgumentParser(description="Plot trajectories generated by Knot model")
    parser.add_argument("--dataset", choices=["knot"], default="knot")
    parser.add_argument("--model-type", choices=["teacher", "student"], required=True)
    parser.add_argument("--checkpoint", type=Path, required=True, help="Path to checkpoint")
    parser.add_argument("--output", type=Path, default=Path("outputs/knot_trajectories.png"))
    parser.add_argument("--num-trajectories", type=int, default=100)
    parser.add_argument("--num-steps", type=int, default=100)
    parser.add_argument("--K", type=int, default=60, help="Number of ground truth marginals")
    parser.add_argument("--device", default="auto")
    # W&B args (optional — if not provided, no wandb logging)
    parser.add_argument("--wandb-run-id", default=None, help="W&B run ID to resume and log image into")
    parser.add_argument("--wandb-project", default="flow2pc")
    parser.add_argument("--wandb-run-name", default=None, help="Run name to search for (if no run ID)")
    parser.add_argument("--wandb-group", default=None)
    return parser.parse_args()


@torch.no_grad()
def integrate_rk4_teacher(
    model: torch.nn.Module,
    x0: torch.Tensor,
    num_steps: int = 100,
    device: torch.device = torch.device("cpu"),
) -> torch.Tensor:
    dt = 1.0 / num_steps
    time_steps = torch.linspace(0.0, 1.0, num_steps + 1, device=device)
    trajectories = [x0.clone()]
    current_x = x0.clone()
    for i in range(num_steps):
        t_curr = time_steps[i].expand(current_x.shape[0])
        t_mid = (time_steps[i] + 0.5 * dt).expand(current_x.shape[0])
        t_next = time_steps[i + 1].expand(current_x.shape[0])
        k1 = model(t_curr, current_x)
        k2 = model(t_mid, current_x + 0.5 * dt * k1)
        k3 = model(t_mid, current_x + 0.5 * dt * k2)
        k4 = model(t_next, current_x + dt * k3)
        current_x = current_x + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
        trajectories.append(current_x.clone())
    return torch.stack(trajectories, dim=1)


@torch.no_grad()
def integrate_rk4_student(
    model: torch.nn.Module,
    x0: torch.Tensor,
    num_steps: int = 100,
    device: torch.device = torch.device("cpu"),
) -> torch.Tensor:
    dt = 1.0 / num_steps
    time_steps = torch.linspace(0.0, 1.0, num_steps + 1, device=device)
    trajectories = [x0.clone()]
    current_x = x0.clone()
    for i in range(num_steps):
        t_curr = time_steps[i].expand(current_x.shape[0])
        t_mid = (time_steps[i] + 0.5 * dt).expand(current_x.shape[0])
        t_next = time_steps[i + 1].expand(current_x.shape[0])
        k1 = model.velocity(current_x, t_curr)
        k2 = model.velocity(current_x + 0.5 * dt * k1, t_mid)
        k3 = model.velocity(current_x + 0.5 * dt * k2, t_mid)
        k4 = model.velocity(current_x + dt * k3, t_next)
        current_x = current_x + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
        trajectories.append(current_x.clone())
    return torch.stack(trajectories, dim=1)


def load_model(args, device):
    if args.model_type == "teacher":
        model = ALICFMTeacherWrapper(str(args.checkpoint), map_to_interval=False).to(device)
        model.eval()
        return model
    else:
        checkpoint = torch.load(args.checkpoint, map_location=device, weights_only=False)
        model = build_student(checkpoint["model_config"]).to(device)
        model.load_state_dict(checkpoint["state_dict"])
        model.eval()
        return model


def main():
    args = parse_args()
    device = torch.device(
        ("cuda" if torch.cuda.is_available() else "cpu") if args.device == "auto" else args.device
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)

    print(f"Loading {args.model_type} from {args.checkpoint}...")
    model = load_model(args, device)

    print(f"Generating ground truth Knot distribution (K={args.K})...")
    gt_data = generate_knot_distribution(K=args.K, samples_per_marginal=100)
    K, N, _ = gt_data.shape

    init_indices = torch.randint(0, N, (args.num_trajectories,))
    x0 = gt_data[0, init_indices].to(device)

    print(f"Simulating {args.num_trajectories} trajectories...")
    if args.model_type == "teacher":
        trajectories = integrate_rk4_teacher(model, x0, num_steps=args.num_steps, device=device)
    else:
        trajectories = integrate_rk4_student(model, x0, num_steps=args.num_steps, device=device)

    traj_np = trajectories.cpu().numpy()
    gt_np = gt_data.numpy()

    # ---- Plot ----
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
    fig, ax = plt.subplots(figsize=(8, 8), dpi=150)

    cmap = plt.cm.viridis
    for k in range(K):
        color = cmap(k / (K - 1))
        ax.scatter(gt_np[k, :, 0], gt_np[k, :, 1], color=color, alpha=0.15, s=6)

    for b in range(args.num_trajectories):
        ax.plot(traj_np[b, :, 0], traj_np[b, :, 1], color="crimson", alpha=0.5, linewidth=1.0)

    ax.scatter(traj_np[:, 0, 0], traj_np[:, 0, 1], color="forestgreen", s=30, zorder=5, label="Start")
    ax.scatter(traj_np[:, -1, 0], traj_np[:, -1, 1], color="purple", s=30, zorder=5, label="End")

    # Fixed axis limits for comparable scaling across all sweep runs
    ax.set_xlim(-5, 5)
    ax.set_ylim(-3, 3)
    ax.set_aspect("equal")

    title = f"{args.model_type.capitalize()} ODE Path (Knot)"
    ax.set_title(title, fontsize=14, fontweight="bold")
    ax.set_xlabel("X")
    ax.set_ylabel("Y")
    ax.legend(loc="upper right", frameon=True)

    plt.tight_layout()
    plt.savefig(args.output, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"Plot saved to {args.output}")

    # ---- Quantitative metrics ----
    end_sim = traj_np[:, -1, :]
    end_gt = gt_np[-1]

    mean_mse = float(np.mean((end_sim.mean(axis=0) - end_gt.mean(axis=0)) ** 2))
    var_mse = float(np.mean((end_sim.var(axis=0) - end_gt.var(axis=0)) ** 2))

    with torch.no_grad():
        if args.model_type == "student":
            time_one = torch.tensor(1.0, device=device)
            gt_tensor = torch.from_numpy(end_gt).to(device)
            nll = -model.log_prob(gt_tensor, time_one).mean().item()
        else:
            nll = float("nan")

    print(f"METRIC_MEAN_MSE={mean_mse:.6f}")
    print(f"METRIC_VAR_MSE={var_mse:.6f}")
    print(f"METRIC_NLL_NATS={nll:.6f}")

    # ---- Log image (and metrics) to W&B ----
    run_id = args.wandb_run_id
    if run_id is None and args.wandb_run_name:
        # Try to find the run by name
        api = wandb.Api()
        filters = {"display_name": args.wandb_run_name}
        if args.wandb_group:
            filters["group"] = args.wandb_group
        runs = list(api.runs(args.wandb_project, filters=filters))
        if runs:
            run_id = runs[0].id
        else:
            print(f"[wandb] WARNING: could not find run '{args.wandb_run_name}'; skipping wandb log.")

    if run_id:
        with wandb.init(
            project=args.wandb_project,
            id=run_id,
            resume="must",
        ) as run:
            run.log({
                "eval/student_trajectory": wandb.Image(str(args.output), caption=args.wandb_run_name or run_id),
                "eval/terminal_mean_mse": mean_mse,
                "eval/terminal_var_mse": var_mse,
                "eval/terminal_nll_nats": nll,
            })
        print(f"[wandb] Logged image + metrics to run '{run_id}'")


if __name__ == "__main__":
    main()
